#!/usr/bin/env python3
"""Generate the Vulkan FXAA Quality source and optionally validate both variants.

The pinned NVIDIA/Intel BSD source is vendored; generation never downloads code.
D3D12 already embeds FXAA Quality bytecode (normal=12, extreme=39), and its
binding/constant layout is retained. No game shaders or assets are involved.
"""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'integrations/rexglue/swap-aa'
VENDOR_SHA256 = '4521a64dfdc17770fa7058b5f172bb9ecf7f49a759d23bc7a937406cd9eccc34'
SOURCE_URL = 'https://raw.githubusercontent.com/GameTechDev/CMAA2/d0ec9097335f740c6dd7ea1ff3f4336fc6e11a40/Projects/CMAA2/FXAA/Fxaa3_11.h'

PREFIX = '''#version 450
#define FXAA_PC 1
#define FXAA_GLSL_130 1
#define FXAA_GATHER4_ALPHA 1
#define FXAA_FAST_PIXEL_OFFSET 1
'''
MAIN = '''
layout(local_size_x = 16, local_size_y = 8, local_size_z = 1) in;
layout(push_constant) uniform XeApplyGammaRampConstants {
  uvec2 xe_fxaa_size;
  vec2 xe_fxaa_size_inv;
};
layout(set = 0, binding = 0) uniform sampler2D xe_fxaa_source;
layout(set = 1, binding = 0, rgb10_a2) writeonly uniform image2D xe_fxaa_dest;
void main() {
  uvec2 pixel = gl_GlobalInvocationID.xy;
  if (any(greaterThanEqual(pixel, xe_fxaa_size))) return;
  vec2 uv = (vec2(pixel) + vec2(0.5)) * xe_fxaa_size_inv;
  vec4 value = FxaaPixelShader(uv, vec4(0.0), xe_fxaa_source,
      xe_fxaa_source, xe_fxaa_source, xe_fxaa_source, xe_fxaa_size_inv,
      vec4(0.0), vec4(0.0), vec4(0.0),
      ASTER_SUBPIX, ASTER_EDGE_THRESHOLD, ASTER_EDGE_THRESHOLD_MIN,
      8.0, 0.125, 0.05, vec4(0.0));
  imageStore(xe_fxaa_dest, ivec2(pixel), vec4(value.rgb, 1.0));
}
'''


def sources():
    vendor = (DIRECTORY / 'Fxaa3_11.h').read_bytes()
    if hashlib.sha256(vendor).hexdigest() != VENDOR_SHA256:
        raise ValueError('Vendored FXAA source differs from pinned bytes')
    common = PREFIX + vendor.decode('utf8') + MAIN
    defines = ['#define FXAA_QUALITY__PRESET 12\n#define ASTER_SUBPIX 0.75\n#define ASTER_EDGE_THRESHOLD 0.166\n#define ASTER_EDGE_THRESHOLD_MIN 0.0833\n',
               '#define FXAA_QUALITY__PRESET 39\n#define ASTER_SUBPIX 1.0\n#define ASTER_EDGE_THRESHOLD 0.063\n#define ASTER_EDGE_THRESHOLD_MIN 0.0312\n']
    return [common.replace('#version 450\n', '#version 450\n' + d, 1) for d in defines]


def header_bytes():
    vendor = (DIRECTORY / 'Fxaa3_11.h').read_text()
    # Keep the full upstream copyright/license in the generated SDK source too.
    license_text = '\n'.join(vendor.splitlines()[11:43])
    return ('''// Generated by scripts/generate_swap_aa.py; do not edit.
#pragma once
#include <string>
''' + license_text + '''
namespace rex::graphics::vulkan::aster_fxaa {
inline const char* GetQualitySource(bool extreme) {
  static constexpr const char* source[] = {
''' + ',\n'.join('R"ASTER_FXAA(' + source + ')ASTER_FXAA"' for source in sources()) + '''
  };
  return source[extreme ? 1 : 0];
}
}  // namespace rex::graphics::vulkan::aster_fxaa
''').encode('utf8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--validate', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    header = DIRECTORY / 'fxaa_quality_source.h'
    data = header_bytes()
    if args.check:
        if header.read_bytes() != data: raise ValueError('Generated FXAA header is stale')
    else:
        header.write_bytes(data)
    if args.validate:
        with tempfile.TemporaryDirectory(prefix='aster-fxaa-') as temp:
            for name, source in zip(('normal', 'extreme'), sources()):
                path = Path(temp) / (name + '.comp'); path.write_text(source)
                binary = path.with_suffix('.spv')
                subprocess.run(['glslangValidator', '-V', str(path), '-o', str(binary)], check=True)
                subprocess.run(['spirv-val', str(binary)], check=True)
    print(json.dumps({'source': SOURCE_URL, 'vendor_sha256': VENDOR_SHA256,
                      'generated_sha256': hashlib.sha256(data).hexdigest(), 'validated': args.validate}))


if __name__ == '__main__': main()
